/** Path for a product, so the URL shape lives in exactly one place. */
export const productHref = (p: Pick<Product, "category" | "slug">) =>
  `/catalog/${p.category}/${p.slug}`;

/**
 * The homepage strip. Deliberately the products that have a site-ready
 * photograph, so the one grid on the site where the image *is* the content
 * never shows a placeholder.
 */
export const featuredProducts = products.filter((p) => p.image !== null);

export const productsByCategory = (category: string) =>
  products.filter((p) => p.category === category);

export const findProduct = (category: string, slug: string) =>
  products.find((p) => p.category === category && p.slug === slug);
